`default_nettype none
`timescale 1ns/1ns

// ============================================================================
// TinyGPU M3 Control Execution Unit
// ============================================================================
//
// Purpose
// -----------------------------------------------------------------------------
// Execute Branch, NOP, Wait and end instructions by producing one held
// architectural commit descriptor.
//
// Microarchitecture
// -----------------------------------------------------------------------------
// - One instruction may own the unit at a time.
// - Combinational logic builds the descriptor from the incoming instruction
//   and its saved Context snapshot.
// - A taken SOPP branch uses:
//       target = instruction_pc + 4 + sign_extend(SIMM16) * 4
// - Other instructions use the sequential PC generated by
//   m3_sequential_commit().
// - Wave32 VCC/EXEC conditions inspect only the low 32 bits.
// - Control instructions execute even when EXEC is zero.
//
// State behavior
// -----------------------------------------------------------------------------
// IDLE:
//   Accept one instruction and save its Wave ID and computed descriptor.
//
// SEND:
//   Hold commit_valid, commit_wave_id and commit_payload until accepted.
//
// Commit ownership
// -----------------------------------------------------------------------------
// - This unit produces descriptors; Writeback/Commit performs architectural
//   updates through the M2 interfaces.
// - Wait thresholds are already decoded. Writeback/Commit queries the
//   Dependency Tracker at commit and selects READY or WAITCNT.
// - end is represented by is_end; final Wave retirement is handled downstream.
// ============================================================================

module wave_control_unit #(
    parameter int WAVE_ID_BITS = 2
) (
    input  logic                         clk,
    input  logic                         rst_n,

    input  logic                         issue_valid,
    output logic                         issue_ready,
    input  logic [WAVE_ID_BITS-1:0]      issue_wave_id,
    input  gpu_pkg::m3_operand_payload_t issue_payload,

    output logic                         commit_valid,
    input  logic                         commit_ready,
    output logic [WAVE_ID_BITS-1:0]      commit_wave_id,
    output gpu_pkg::m3_commit_t          commit_payload
);

import gpu_pkg::*;

localparam logic IDLE = 1'b0;
localparam logic SEND = 1'b1;

logic state;
logic next_state;

logic issue_fire;
logic commit_fire;

logic        taken;
logic [63:0] target;
m3_commit_t  computed;

assign issue_ready = (state == IDLE); 
assign commit_valid = (state == SEND);
assign issue_fire = issue_valid && issue_ready;
assign commit_fire = commit_valid && commit_ready;

always_ff @(posedge clk or negedge rst_n)begin
	if (!rst_n)begin
		state <= IDLE;
	end
	else  begin
		state <= next_state;
	end
end
always_comb begin
	next_state = state;
	case(state)
		IDLE    : begin next_state = issue_fire ? SEND : IDLE; end
		SEND    : begin next_state = commit_fire ?  IDLE : SEND; end
		default : begin next_state = IDLE; end
	endcase
end

always_ff @ (posedge clk or negedge rst_n)begin
	if (!rst_n)begin
		commit_payload <= '0;
		commit_wave_id   <= '0;
	end
	else begin
		if (issue_fire)begin
		commit_wave_id <= issue_wave_id;
		commit_payload <= computed;
		end
	
	end
end

always_comb begin
	taken = '0;
	computed = m3_sequential_commit(issue_payload.decoded);
	target = issue_payload.decoded.context_data.pc
       + 64'd4
       + ({{32{issue_payload.decoded.uop.immediate[31]}},
           issue_payload.decoded.uop.immediate} << 2);
	case (issue_payload.decoded.uop.branch_condition)
		BRANCH_CONDITION_ALWAYS : begin
			taken = 1'b1;
		end
		BRANCH_CONDITION_SCC0 : begin
			taken = !issue_payload.decoded.context_data.scc;
		end
		BRANCH_CONDITION_SCC1 : begin
			taken = issue_payload.decoded.context_data.scc;
		end
		BRANCH_CONDITION_VCCZ : begin
			taken = !(|issue_payload.decoded.context_data.vcc[31:0]);
		end
		BRANCH_CONDITION_VCCNZ : begin
			taken = (|issue_payload.decoded.context_data.vcc[31:0]);
		end
		BRANCH_CONDITION_EXECZ : begin
			taken = !(|issue_payload.decoded.context_data.exec_mask[31:0]);
		end
		BRANCH_CONDITION_EXECNZ : begin
			taken = (|issue_payload.decoded.context_data.exec_mask[31:0]);
		end
		default :begin
			taken = '0;
		end	
	endcase
	if ((issue_payload.decoded.uop.uop_class == UOP_CLASS_BRANCH)
    && taken) begin
    computed.next_pc = {7'b0, target[56:2], 2'b0};
	end
end



endmodule

`default_nettype wire